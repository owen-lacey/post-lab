import { z } from 'zod';
import { ALIGNS, COLORS, SIZES } from '../shared/palette';
import { ITEM_SCHEMAS, type ItemType } from '../shared/schemas';

type JsonSchema = z.core.JSONSchema.JSONSchema;

/** What the markdown body after the frontmatter holds, per item type. */
const BODY: Record<ItemType, string> = {
  note: 'The sticky note text, shown as typed (markdown is not rendered).',
  text: 'The text, shown as typed (markdown is not rendered).',
  shape: 'Label shown inside the shape. May be empty.',
  frame: 'Title shown above the frame. May be empty.',
  image: 'Caption. May be empty.',
  link: 'A note about the link. May be empty.',
  cell: 'What the cell shows. May be empty.',
  connector: 'Label shown on the line. May be empty.',
};

const code = (value: unknown) => `\`${String(value)}\``;

function describeType(property: JsonSchema): string {
  if (property.const !== undefined) return code(property.const);
  if (property.enum !== undefined) return `one of ${property.enum.map(code).join(', ')}`;
  if (property.type === 'object') {
    return `object with ${Object.keys(property.properties ?? {})
      .map(code)
      .join(', ')}`;
  }
  if (property.type === 'integer') {
    return property.exclusiveMinimum === 0 ? 'positive integer' : 'integer';
  }
  if (property.format === 'uri') return 'URL';
  if (property.pattern === '^[0-9a-z]{8}$') return 'item ID';
  return String(property.type);
}

function fieldTable(type: ItemType): string {
  const schema = z.toJSONSchema(ITEM_SCHEMAS[type]);
  const required = new Set(schema.required);
  const rows = Object.entries(schema.properties ?? {}).map(([name, property]) => {
    const details = typeof property === 'boolean' ? {} : property;
    const cells = [
      code(name),
      describeType(details),
      required.has(name) ? 'yes' : 'no',
      details.description ?? '',
    ];
    return `| ${cells.join(' | ')} |`;
  });
  return ['| Field | Value | Required | Meaning |', '|---|---|---|---|', ...rows].join('\n');
}

function typeSection(type: ItemType): string {
  return `### \`${type}\`\n\n${fieldTable(type)}\n\nBody: ${BODY[type]}`;
}

const INTRO = `<!-- Generated by post-lab on every launch. Do not edit: your changes will be lost. -->

# post-lab board

**This file is generated by post-lab every time it starts. Hand edits are lost.**

This folder is the post-lab board for this repo: a canvas of notes, text, shapes, frames, images, links, code cells and connectors, opened with \`npx post-lab\` from the repo root. To change the board, edit the files in this folder. post-lab shows them as they are on disk, and an open board updates as soon as a file is saved.

## Layout

\`\`\`
.post-lab/
  README.md            this guide (generated)
  items/<id>.md        one file per item
  strokes.json         freehand drawing (written by post-lab; do not edit by hand)
  assets/<file>        images shown by image items
  outputs/<cell-id>/   files written by code cells
\`\`\`

## Item files

- Each item is one file, \`items/<id>.md\`. The ID is 8 characters from \`0-9\` and \`a-z\`, for example \`k3f9a0qz\`. To add an item, pick a random ID that is not already used. IDs never change.
- A file is YAML frontmatter between two \`---\` lines, then the body: the item's text. The body may be empty, in which case nothing follows the closing \`---\` line.
- Fields are listed below per \`type\`. Unknown fields are errors. A file with an error is not shown on the canvas; post-lab lists it in its Problems panel with the reason.
- Positions and sizes are whole numbers of canvas pixels. \`x\` grows to the right and \`y\` grows downwards.
- Frames group items. To put an item in a frame, set \`frame: <frame id>\`; its \`x\` and \`y\` are then relative to the frame's top-left corner. Frames cannot be inside frames.
- Connectors are lines between two items, named by ID in \`from\` and \`to\`. They have no position.
- Style tokens: \`color\` is one of ${COLORS.map(code).join(', ')}; \`size\` is one of ${SIZES.map(code).join(', ')}; \`align\` is one of ${ALIGNS.map(code).join(', ')}.

## Example

A note, \`items/n0te0001.md\`:

\`\`\`markdown
---
type: note
x: 0
y: 0
w: 200
h: 160
color: yellow
---
Open with the churn chart.
\`\`\`

A connector from that note to the item \`c3ll0001\`, \`items/l1nk0001.md\`:

\`\`\`markdown
---
type: connector
from: n0te0001
to: c3ll0001
---
shows
\`\`\`

## Cells and outputs

- A \`cell\` item runs \`command\` through the shell, in \`cwd\` (relative to the repo root; default the repo root). It runs only when someone clicks Run in post-lab, never because its file changed.
- Each run first empties \`outputs/<cell id>/\`, then sets the environment variable \`POST_LAB_OUT\` to that folder's absolute path. Scripts write their results there, e.g. \`fig.write_html(os.environ["POST_LAB_OUT"] + "/churn.html")\`.
- Whatever the command prints to stdout is saved there as \`stdout.txt\`. stderr and a non-zero exit code are shown in post-lab but not saved.
- Outputs are committed with the repo, so the board shows them without running anything.
- Every file in the folder is shown, sorted by name. Its extension decides how:

| File | Shown as |
|---|---|
| \`.png\`, \`.jpg\`, \`.jpeg\`, \`.gif\`, \`.webp\`, \`.svg\` | image |
| \`.csv\` | table, first line as the header |
| \`.json\` | table; must be an array of objects |
| \`.vl.json\` | Vega-Lite chart; a relative \`data.url\` is read from the same folder |
| \`.html\` | interactive page (e.g. Plotly) in a sandboxed frame |
| \`.md\` | rendered markdown (GitHub flavoured); relative links point into the same folder |
| \`stdout.txt\` | text |
| anything else | a link to the file |

## Field reference`;

/** The agent guide (D11), with the field reference generated from the item schemas (D13). */
export function renderGuide(): string {
  const types = Object.keys(ITEM_SCHEMAS) as ItemType[];
  return `${[INTRO, ...types.map(typeSection)].join('\n\n')}\n`;
}
