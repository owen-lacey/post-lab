import { readFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { ITEM_SCHEMAS } from '../shared/schemas';
import { renderGuide } from './guide';
import { boardExists, createBoard, writeGuide } from './host';
import { makeHost } from './test-helpers';

describe('host board folder', () => {
  it('creates .post-lab/items/ when asked, and only then', async () => {
    const hostRoot = await makeHost();
    expect(await boardExists(hostRoot)).toBe(false);
    await createBoard(hostRoot);
    expect(await boardExists(hostRoot)).toBe(true);
    expect((await stat(join(hostRoot, '.post-lab/items'))).isDirectory()).toBe(true);
  });

  it('does not count a .post-lab file as a board', async () => {
    expect(await boardExists(await makeHost({ '.post-lab': '' }))).toBe(false);
  });

  it('rewrites the guide over hand edits', async () => {
    const hostRoot = await makeHost({ '.post-lab/README.md': 'hand edit' });
    await writeGuide(hostRoot);
    expect(await readFile(join(hostRoot, '.post-lab/README.md'), 'utf8')).toBe(renderGuide());
  });
});

describe('agent guide', () => {
  const guide = renderGuide();

  it('says it is generated before anything else', () => {
    expect(guide.split('\n', 1)[0]).toContain('Generated by post-lab');
  });

  it('documents every item type and every field from the schemas', () => {
    for (const [type, schema] of Object.entries(ITEM_SCHEMAS)) {
      expect(guide).toContain(`### \`${type}\``);
      for (const field of Object.keys(schema.shape)) {
        expect(guide).toContain(`| \`${field}\` |`);
      }
    }
  });

  it('lists the palette and enum values', () => {
    expect(guide).toContain('`purple`');
    expect(guide).toContain('one of `rectangle`, `ellipse`, `diamond`');
  });
});
